def write(run: dict) -> Path:
    folder = runs_dir() / run["run_id"]
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "result.json").write_text(json.dumps(run, indent=2), encoding="utf-8")
    (folder / "report.html").write_text(html_report(run), encoding="utf-8")
    (folder / "latest").write_text(run["run_id"], encoding="utf-8")
    return folder


def latest() -> dict | None:
    root = runs_dir()
    pointer = root / "latest"
    if not pointer.exists():
        return None
    path = root / pointer.read_text(encoding="utf-8").strip() / "result.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def previous(exclude: str) -> dict | None:
    """Most recent finished run before the given one (for baseline comparison)."""
    root = runs_dir()
    runs = sorted((p for p in root.iterdir() if p.is_dir() and p.name != exclude), reverse=True)
    for folder in runs:
        data = folder / "result.json"
        if data.exists():
            try:
                return json.loads(data.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                continue
    return None


def compare(current: dict, baseline: dict) -> list[dict]:
    was = {c["id"]: c for c in baseline.get("cases", [])}
    out = []
    for case in current["cases"]:
        old = was.get(case["id"])
        if old is None:
            out.append({"id": case["id"], "change": "new", "tokens_delta": 0})
            continue
        if old["ok"] and not case["ok"]:
            change = "regression"
        elif not old["ok"] and case["ok"]:
            change = "fixed"
        else:
            change = "stable"
        out.append(
            {
                "id": case["id"],
                "change": change,
                "tokens_delta": case.get("tokens", 0) - old.get("tokens", 0),
            }
        )
    return out


def compare_table(diff: list[dict]) -> str:
    interesting = [d for d in diff if d["change"] != "stable" or d["tokens_delta"]]
    if not interesting:
        return ""
    lines = ["", "CHANGE vs previous run"]
    for d in interesting:
        lines.append(f"  {d['id'][:26].ljust(28)}{d['change'].ljust(12)}{d['tokens_delta']:+,} tokens")
    return "\n".join(lines)
