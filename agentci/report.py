"""Reports: a terminal table for the humans, HTML for the repo, JSON for CI."""

from __future__ import annotations

import html
import json
import time
from pathlib import Path

from .paths import runs_dir


def summarize(results: list[dict]) -> dict:
    passed = [r for r in results if r["ok"]]
    return {
        "total": len(results),
        "passed": len(passed),
        "failed": len(results) - len(passed),
        "tokens": sum(r.get("tokens", 0) for r in results),
        "duration_s": round(sum(r.get("duration_s", 0) for r in results), 1),
        "cost_usd": round(sum(r.get("cost_usd", 0) for r in results), 6),
    }


def table(results: list[dict]) -> str:
    rows = ["CASE".ljust(28) + "RESULT".ljust(8) + "TOKENS".rjust(9) + "TIME".rjust(8) + "  DETAIL"]
    for r in results:
        status = "pass" if r["ok"] else "FAIL"
        detail = ""
        if not r["ok"]:
            bad = [c for c in r["checks"] if not c["ok"]]
            detail = bad[0]["detail"] if bad else ("timeout" if r.get("timed_out") else "failed")
        rows.append(
            r["id"][:26].ljust(28)
            + status.ljust(8)
            + f"{r.get('tokens', 0):,}".rjust(9)
            + f"{r.get('duration_s', 0):.1f}s".rjust(8)
            + "  " + detail[:70]
        )
    s = summarize(results)
    rows.append("-" * 78)
    rows.append(f"{s['passed']}/{s['total']} passed · {s['tokens']:,} tokens · {s['duration_s']}s · ${s['cost_usd']:.4f}")
    return "\n".join(rows)


