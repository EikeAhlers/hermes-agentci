        rows.append(
            f"<tr><td><code>{html.escape(case['id'])}</code></td>"
            f"<td style='color:{colour};font-weight:600'>{'PASS' if case['ok'] else 'FAIL'}</td>"
            f"<td>{case['tokens']:,}</td><td>{case['duration_s']:.1f}s</td>"
            f"<td><details><summary>{len(case['checks'])} checks</summary><ul>{checks}</ul>"
            f"<pre>{html.escape((case.get('answer') or '')[:600])}</pre></details></td></tr>"
        )
